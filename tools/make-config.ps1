# Reads SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY from .env.local and writes js/config.local.js.
# The app is opened straight from disk, so it cannot read .env files; this copies the values into a script it can load.
# Both files are in .gitignore and are not pushed to the repository.
# (Kept ASCII-only: Windows PowerShell 5.1 misreads non-ASCII text in BOM-less scripts.)
# Run: powershell -ExecutionPolicy Bypass -File tools\make-config.ps1

$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env.local'
if (-not (Test-Path $envFile)) { Write-Error ".env.local not found: $envFile"; exit 1 }

$vals = @{}
foreach ($line in Get-Content $envFile -Encoding UTF8) {
  if ($line -match '^\s*([A-Z_]+)\s*=\s*(.*?)\s*$') { $vals[$matches[1]] = $matches[2].Trim('"', "'") }
}
foreach ($k in 'SUPABASE_URL', 'SUPABASE_PUBLISHABLE_KEY') {
  if (-not $vals[$k]) { Write-Error "$k is missing in .env.local"; exit 1 }
}

$js = @"
// Generated by tools/make-config.ps1 from .env.local. Do not edit; change .env.local and run the script again.
window.RC_CONFIG = {
  supabaseUrl: '$($vals['SUPABASE_URL'])',
  supabaseKey: '$($vals['SUPABASE_PUBLISHABLE_KEY'])'
};
"@
$out = Join-Path $root 'js\config.local.js'
[IO.File]::WriteAllText($out, $js, (New-Object Text.UTF8Encoding($false)))
Write-Output "Wrote $out"
